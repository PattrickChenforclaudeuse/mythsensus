/**
 * Two-pass bulk editor for the live site:
 *  1. Remove every "Open App →" / "Reveal My Score" / "Open the App" CTA
 *     button from blog/landing/pricing/support/disclaimer pages.
 *  2. Inject a compact AI-disclaimer line at the top of every <footer>
 *     (or equivalent bottom block) on all pages.
 *
 * Skips /beta/index.html (that IS the app — the "← Back" pill there is
 * fine, no "Open App" inside anyway).
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = 'C:/Users/CHAIYAPAT/Documents/GitHub/mythsensus';
const SKIP = new Set(['beta/index.html']);

const DISCLAIMER_BLOCK_MARKER = 'site-disclaimer-v1';
const DISCLAIMER_HTML = `  <div class="${DISCLAIMER_BLOCK_MARKER}" style="max-width:780px;margin:0 auto;padding:18px 16px;border-top:1px solid rgba(200,164,90,.18);text-align:center;font-family:'Josefin Sans',sans-serif;font-size:10px;letter-spacing:1.4px;color:rgba(200,164,90,.55);line-height:1.7;text-transform:none">
    <span data-en="Mythsensus content is generated by AI for entertainment, self-exploration, and personal reflection. It is not medical, legal, financial, or psychological advice. The stars may illuminate the path — the steps remain yours alone." data-th="เนื้อหา Mythsensus สร้างโดย AI เพื่อความบันเทิง การสำรวจตนเอง และการใคร่ครวญส่วนบุคคล ไม่ใช่คำแนะนำทางการแพทย์ กฎหมาย การเงิน หรือจิตวิทยา ดวงดาวอาจส่องทาง — ก้าวเดินเป็นของคุณ">Mythsensus content is generated by AI for entertainment, self-exploration, and personal reflection. It is not medical, legal, financial, or psychological advice. The stars may illuminate the path — the steps remain yours alone.</span>
    <br><a href="/disclaimer" style="color:var(--gold,#c8a45a);text-decoration:underline;opacity:.8" data-en="Read the full disclaimer →" data-th="อ่านข้อจำกัดฉบับเต็ม →">Read the full disclaimer →</a>
  </div>
`;

// ── 1) STRIP "Open App" CTAs ─────────────────────────────────────────
// We match and remove whole <a ...>...</a> nodes whose text is Open App
// or equivalent. Done conservatively — only nodes that point at /beta/.
// Patterns, in rough order:
//   - btn-gold / tier-cta Open App CTA
//   - inline Read blog-footer link to /beta
function stripOpenApp(html) {
  let out = html;
  let hits = 0;
  // 1a. Strong CTA button in blog + landing + pricing + support + disclaimer navs.
  //     Match any single <a> with href="/beta/" whose inner text contains Open App.
  out = out.replace(
    /<a[^>]*href=["']\/beta\/?["'][^>]*>(?:\s|\S)*?<\/a>/g,
    (match) => {
      if (/Open\s*App|Open the App|เปิดแอป|Try Free in Beta|ลองฟรีในช่วงทดสอบ|Reveal\s*My\s*Score|เผย\s*Cosmic\s*Score|Redeem|ใช้รหัส/i.test(match)) {
        hits++;
        return '';
      }
      return match;
    }
  );
  // 1b. Article footer CTA block: <div class="cta-block"> ... </div> — strip entire block.
  out = out.replace(
    /<div class="cta-block"[\s\S]*?<\/div>\s*/g,
    (m) => {
      if (/Open\s*App|เปิดแอป|Reveal/i.test(m)) { hits++; return ''; }
      return m;
    }
  );
  return { html: out, hits };
}

// ── 2) INJECT DISCLAIMER INTO FOOTER ─────────────────────────────────
// Finds the first of: <footer...>, <div class="footer-blog">, <div class="footer-*">, or
// just body close. Inserts DISCLAIMER_HTML immediately before that block
// (so it appears ABOVE any existing footer). Idempotent via marker.
function injectDisclaimer(html) {
  if (html.includes(DISCLAIMER_BLOCK_MARKER)) return { html, injected: false };
  // Preferred target: opening of <footer> tag
  let re = /<footer\b[^>]*>/i;
  let m = html.match(re);
  if (m) {
    const i = html.indexOf(m[0]);
    return { html: html.slice(0, i) + DISCLAIMER_HTML + html.slice(i), injected: true };
  }
  // Fallback: .footer-blog wrapper (blog + article pages)
  re = /<div class="footer-blog\b[^>]*"[^>]*>/i;
  m = html.match(re);
  if (m) {
    const i = html.indexOf(m[0]);
    return { html: html.slice(0, i) + DISCLAIMER_HTML + html.slice(i), injected: true };
  }
  // Fallback: main landing has custom <footer style="...">; already handled.
  // Last resort: insert before </body>.
  re = /<\/body>/i;
  m = html.match(re);
  if (m) {
    const i = html.indexOf(m[0]);
    return { html: html.slice(0, i) + DISCLAIMER_HTML + html.slice(i), injected: true };
  }
  return { html, injected: false };
}

// ── FILE WALKER ──────────────────────────────────────────────────────
function walk(dir, out=[]) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const st = fs.statSync(full);
    if (st.isDirectory()) {
      if (name === 'node_modules' || name === '.git' || name === '.vercel') continue;
      walk(full, out);
    } else if (name.endsWith('.html')) {
      out.push(full);
    }
  }
  return out;
}

const files = walk(ROOT);
let totalHits = 0, totalInj = 0, filesTouched = 0;

for (const file of files) {
  const rel = file.replace(ROOT + '\\', '').replace(/\\/g, '/').replace(/^[/\\]/, '');
  if (SKIP.has(rel)) { console.log(`skip  ${rel}`); continue; }

  let html = fs.readFileSync(file, 'utf-8');
  const stripped = stripOpenApp(html);
  html = stripped.html;
  const injected = injectDisclaimer(html);
  html = injected.html;

  const changed = (stripped.hits > 0) || injected.injected;
  if (changed) {
    fs.writeFileSync(file, html);
    filesTouched++;
    totalHits += stripped.hits;
    if (injected.injected) totalInj++;
    console.log(`✓ ${rel}  — stripped:${stripped.hits} disclaimer:${injected.injected?'added':'skip'}`);
  } else {
    console.log(`—  ${rel}  (no change)`);
  }
}
console.log(`\n${filesTouched} files touched · ${totalHits} Open-App CTAs removed · ${totalInj} disclaimers injected`);
